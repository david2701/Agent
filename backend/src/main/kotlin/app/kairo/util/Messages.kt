    /** The text in [lang] with `{0}`, `{1}`... replaced by [args]. */
    fun t(lang: Lang, vararg args: Any?): String = render(if (lang == Lang.ES) es else en, args)

    companion object {
        private val PLACEHOLDER = Regex("\\{(\\d+)}")

        internal fun render(template: String, args: Array<out Any?>): String =
            if (args.isEmpty()) template
            else PLACEHOLDER.replace(template) { m -> args.getOrNull(m.groupValues[1].toInt())?.toString().orEmpty() }

        /** Placeholder indexes used by [template], for the catalog consistency test. */
        fun placeholders(template: String): Set<Int> = PLACEHOLDER.findAll(template).map { it.groupValues[1].toInt() }.toSet()
    }
