/** Something that can describe itself in the language of whoever will read it. */
interface Localizable {
    fun text(lang: Lang): String
}

/** Text that is already final (user content, names): it reads the same in every language. */
class Plain(val value: String) : Localizable {
    override fun text(lang: Lang): String = value
    override fun toString(): String = value
}

/** Text built from the reader's language, for pieces that depend on it (dates, for example). */
fun localized(block: (Lang) -> String): Localizable = object : Localizable {
    override fun text(lang: Lang): String = block(lang)
}

/**
 * A catalog message with its arguments, rendered later in the reader's language. An argument that is itself
 * [Localizable] is rendered in the same language.
 */
class Say(val msg: M, val args: List<Any?> = emptyList()) : Localizable {
    override fun text(lang: Lang): String = msg.t(lang, *args.map { if (it is Localizable) it.text(lang) else it }.toTypedArray())
    override fun toString(): String = text(Lang.EN)
}

fun say(msg: M, vararg args: Any?): Say = Say(msg, args.toList())

/**
 * A validation failure whose text is meant for the person (the Kairo-side equivalent of `require`).
 * `message` is the English text (logs, tests); [text] renders it in the reader's language.
 */
open class InvalidInput(val msg: M, val args: List<Any?> = emptyList()) : IllegalArgumentException(Say(msg, args).text(Lang.EN)), Localizable {
    override fun text(lang: Lang): String = Say(msg, args).text(lang)
}

fun invalid(msg: M, vararg args: Any?): Nothing = throw InvalidInput(msg, args.toList())

fun requireInput(condition: Boolean, msg: M, vararg args: Any?) {
    if (!condition) throw InvalidInput(msg, args.toList())
}
